"""No-prompt admin repairs for Autopilot. Off by default; the person sets it up once.

Windows asks for permission every time something wants administrator rights. For Autopilot to run
an admin repair with nobody at the PC, the person agrees once, from their own administrator
account: one Windows prompt installs a small, fixed set of scheduled tasks that run elevated.

What gets installed (and removed again when the option is switched off):
  - %ProgramFiles%\\SystemAutoBot\\admin\\repair.ps1: the only code that runs elevated. It sits where
    only administrators can write, is run by Windows' own powershell.exe, takes one argument (which
    repair), and holds the commands for exactly the repairs in UNATTENDED. Nothing else is passed in.
  - One scheduled task per repair, "run with highest privileges", for this Windows user.
  - Results go to %ProgramData%\\SystemAutoBot\\runs, which only administrators can write.

The trade-off, stated in Settings before it is switched on: once installed, any program running in
this Windows account could start these repairs without a prompt. That is why the list is short and
harmless (no restarts, no deletions, nothing to undo), and why it is never installed unasked.
"""

from __future__ import annotations

import base64
import hashlib
import logging
import os
import re
import subprocess
import sys
from pathlib import Path

from .tools.fixes import UNATTENDED

log = logging.getLogger("systemautobot.admin_setup")

TASK_FOLDER = "\\SystemAutoBot\\"
MAX_COMMAND = 30000  # Windows allows about 32,767 characters on a command line
CREATE_NO_WINDOW = 0x08000000

# What each no-prompt repair does, for Settings.
WORDS = {
    "time_sync": "set the clock",
    "restart_print_spooler": "restart the print service",
    "defender_signature_update": "update virus definitions",
    "firewall_enable": "turn the firewall back on",
    "check_disk": "check the drive for errors",
}


def script_path() -> Path:
    return Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "SystemAutoBot" / "admin" / "repair.ps1"


def task_name(entry: str) -> str:
    return f"{TASK_FOLDER}Repair {entry}"


# ---- the one script that runs elevated ---------------------------------------------------------

def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _exe(name: str) -> str:
    """A PowerShell expression for the program's full path. Never a bare name: no PATH lookups."""
    if "\\" in name or "/" in name:
        return _q(name)  # already a full path under Program Files (MpCmdRun.exe)
    if name.lower() == "powershell.exe":
        return "(Join-Path $env:SystemRoot 'System32\\WindowsPowerShell\\v1.0\\powershell.exe')"
    return f"(Join-Path $env:SystemRoot {_q('System32' + chr(92) + name)})"


def repair_script() -> str:
    """repair.ps1, generated from the same allowlist the prompted helper uses, for UNATTENDED only."""
    from sab_helper.helper import ALLOWLIST

    blocks = []
    for entry in UNATTENDED:
        spec = ALLOWLIST[entry]
        extra = set(spec) - {"summary", "commands", "settings"}
        if extra:  # restore points, restarts and special logic never run unattended
            raise ValueError(f"{entry} is not simple enough to run unattended: {sorted(extra)}")
        commands = []
        for argv, ok_codes, timeout in spec["commands"]:
            if any('"' in a for a in argv):
                raise ValueError(f"{entry}: arguments may not contain double quotes")
            args = ", ".join(_q(a) for a in argv[1:])
            commands.append(f"      @{{ Exe = {_exe(argv[0])}; Args = @({args}); Ok = @({', '.join(str(c) for c in sorted(ok_codes))}); "
                            f"Timeout = {int(timeout)} }}")
        settings = ", ".join(
            f"@{{ kind = {_q(kind)}; name = {_q(name)}; old = {_q(old) if old is not None else '$null'}; new = {_q(new)} }}"
            for kind, name, old, new in spec.get("settings", []))
        blocks.append(f"  {_q(entry)} = @{{\n    Summary = {_q(spec['summary'])}\n    Settings = @({settings})\n"
                      f"    Commands = @(\n" + ",\n".join(commands) + "\n    )\n  }")
    return _REPAIR_HEAD + "$Repairs = @{\n" + "\n".join(blocks) + "\n}\n" + _REPAIR_BODY


_REPAIR_HEAD = """# SystemAutoBot: the repairs Autopilot may run without the Windows prompt.
# Generated by the app and installed by you. Don't edit it: the app compares this file with its
# own copy and asks for setup again if they differ. Switching the option off removes it.
param([Parameter(Mandatory = $true)][string]$Entry)
$ErrorActionPreference = 'Stop'
"""

_REPAIR_BODY = """if (-not $Repairs.ContainsKey($Entry)) { exit 2 }
$me = New-Object Security.Principal.WindowsPrincipal ([Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $me.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { exit 3 }
function Quote-Arg([string]$a) { if ($a -match '\\s') { '"' + $a + '"' } else { $a } }
$spec = $Repairs[$Entry]
$steps = @()
$ok = $true
foreach ($c in $spec.Commands) {
  $psi = New-Object System.Diagnostics.ProcessStartInfo
  $psi.FileName = $c.Exe
  $psi.Arguments = (($c.Args | ForEach-Object { Quote-Arg $_ }) -join ' ')
  $psi.UseShellExecute = $false
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  $psi.CreateNoWindow = $true
  $code = -1
  $out = ''
  try {
    $p = [System.Diagnostics.Process]::Start($psi)
    $o = $p.StandardOutput.ReadToEndAsync()
    $e = $p.StandardError.ReadToEndAsync()
    if ($p.WaitForExit($c.Timeout * 1000)) { $p.WaitForExit(); $code = $p.ExitCode; $out = $o.Result + $e.Result }
    else { try { $p.Kill() } catch {}; $out = 'Timed out.' }
  } catch { $out = $_.Exception.Message }
  if ($out.Length -gt 500) { $out = $out.Substring($out.Length - 500) }
  $steps += @{ command = ((Split-Path $c.Exe -Leaf) + ' ' + ($c.Args -join ' ')); exit_code = $code; output = $out }
  if ($c.Ok -notcontains $code) { $ok = $false; break }
}
$summary = $spec.Summary
if (-not $ok) { $summary = "Couldn't finish: " + $summary.Substring(0, 1).ToLower() + $summary.Substring(1) }
$settings = @()
if ($ok) { $settings = @($spec.Settings) }
$status = 'couldnt'
if ($ok) { $status = 'done' }
$result = @{ entry = $Entry; run_id = "task-$Entry"; status = $status; summary = $summary; steps = $steps
             settings = $settings; needs_restart = $false; undo = $null }
$dir = Join-Path $env:ProgramData 'SystemAutoBot\\runs'
New-Item -ItemType Directory -Force -Path $dir | Out-Null
$json = ConvertTo-Json $result -Depth 6
[System.IO.File]::WriteAllText((Join-Path $dir "task-$Entry.json"), $json, (New-Object System.Text.UTF8Encoding $false))
if ($ok) { exit 0 } else { exit 4 }
"""


# ---- install and remove (each is one Windows prompt) --------------------------------------------

# SYSTEM and Administrators: full control. Users: read and run only. Written as SIDs so it works in every language.
_LOCK = "@('/inheritance:r', '/grant:r', '*S-1-5-18:(OI)(CI)F', '*S-1-5-32-544:(OI)(CI)F', '*S-1-5-32-545:(OI)(CI)RX')"


def setup_script(user: str) -> str:
    """Runs elevated, once. Installs repair.ps1 where only administrators can write, then one task per repair."""
    if not re.fullmatch(r"[\w .$-]{1,64}\\[\w .$-]{1,64}", user):
        raise ValueError("Unexpected Windows account name.")
    body = repair_script()
    if "\n'@" in body:
        raise ValueError("The repair script can't be embedded safely.")
    entries = ", ".join(_q(e) for e in UNATTENDED)
    return f"""$ErrorActionPreference = 'Stop'
$user = {_q(user)}
$root = Join-Path $env:ProgramFiles 'SystemAutoBot\\admin'
$runs = Join-Path $env:ProgramData 'SystemAutoBot\\runs'
$icacls = Join-Path $env:SystemRoot 'System32\\icacls.exe'
if ([Security.Principal.WindowsIdentity]::GetCurrent().Name -ne $user) {{ exit 5 }}  # set up from your own account
$lock = {_LOCK}
foreach ($dir in @($root, $runs)) {{
  New-Item -ItemType Directory -Force -Path $dir | Out-Null
  & $icacls $dir @lock | Out-Null
  if ($LASTEXITCODE -ne 0) {{ exit 7 }}  # couldn't lock the folder: install nothing
}}
$script = @'
{body}'@
[System.IO.File]::WriteAllText((Join-Path $root 'repair.ps1'), $script, (New-Object System.Text.UTF8Encoding $false))
$ps = Join-Path $env:SystemRoot 'System32\\WindowsPowerShell\\v1.0\\powershell.exe'
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Highest
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -MultipleInstances IgnoreNew -ExecutionTimeLimit (New-TimeSpan -Hours 2)
foreach ($entry in @({entries})) {{
  $arg = '-NoProfile -NonInteractive -ExecutionPolicy Bypass -File "' + (Join-Path $root 'repair.ps1') + '" -Entry ' + $entry
  $action = New-ScheduledTaskAction -Execute $ps -Argument $arg
  Register-ScheduledTask -TaskPath {_q(TASK_FOLDER)} -TaskName "Repair $entry" -Action $action -Principal $principal -Settings $settings -Force -Description 'SystemAutoBot Autopilot: one fixed repair with no prompt. Switch the option off in SystemAutoBot to remove it.' | Out-Null
}}
exit 0
"""


def remove_script() -> str:
    return f"""$ErrorActionPreference = 'Continue'
Get-ScheduledTask -TaskPath {_q(TASK_FOLDER)} -ErrorAction SilentlyContinue | Unregister-ScheduledTask -Confirm:$false
try {{ $svc = New-Object -ComObject Schedule.Service; $svc.Connect(); $svc.GetFolder('\\').DeleteFolder('SystemAutoBot', 0) }} catch {{}}
$root = Join-Path $env:ProgramFiles 'SystemAutoBot'
Remove-Item (Join-Path $root 'admin') -Recurse -Force -ErrorAction SilentlyContinue
if ((Test-Path $root) -and -not (Get-ChildItem $root -Force)) {{ Remove-Item $root -Force -ErrorAction SilentlyContinue }}
if (Test-Path (Join-Path $root 'admin\\repair.ps1')) {{ exit 6 }}
exit 0
"""


def encoded(script: str) -> str:
    """PowerShell's -EncodedCommand form. The script travels on the command line, so there is no
    file on disk that another program could change between writing it and the Windows prompt."""
    out = base64.b64encode(script.encode("utf-16-le")).decode("ascii")
    if len(out) > MAX_COMMAND:
        raise ValueError("The setup script is too long for one command line.")
    return out


def account_is_admin() -> bool:
    """Is this Windows account an administrator (even though the app itself never runs elevated)?"""
    if sys.platform != "win32":
        return False
    try:
        import win32api
        import win32con
        import win32security

        token = win32security.OpenProcessToken(win32api.GetCurrentProcess(), win32con.TOKEN_QUERY)
        return win32security.GetTokenInformation(token, win32security.TokenElevationType) in (2, 3)  # full, or limited by UAC
    except Exception:
        return False


def current_user() -> str:
    import win32api
    import win32con

    return win32api.GetUserNameEx(win32con.NameSamCompatible)


def _same(a: str, b: str) -> bool:
    norm = lambda s: s.replace("\r\n", "\n").strip()  # noqa: E731
    return hashlib.sha256(norm(a).encode()).digest() == hashlib.sha256(norm(b).encode()).digest()


def installed() -> bool:
    """True only if the installed script is exactly the one this version of the app would install."""
    try:
        path = script_path()
        return path.is_file() and _same(path.read_text(encoding="utf-8"), repair_script())
    except (OSError, ValueError, UnicodeDecodeError):
        return False


def _elevated(script: str, timeout: float = 300.0) -> tuple[bool, str]:
    """Run one script elevated. This is the single Windows prompt the person agrees to."""
    if sys.platform != "win32":
        return False, "This needs Windows."
    import pywintypes
    import win32con
    import win32event
    import win32process
    from win32com.shell import shell, shellcon

    ps = str(Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "WindowsPowerShell" / "v1.0" / "powershell.exe")
    params = f"-NoProfile -NonInteractive -ExecutionPolicy Bypass -WindowStyle Hidden -EncodedCommand {encoded(script)}"
    try:
        info = shell.ShellExecuteEx(fMask=shellcon.SEE_MASK_NOCLOSEPROCESS, lpVerb="runas", lpFile=ps,
                                    lpParameters=params, nShow=win32con.SW_HIDE)
    except pywintypes.error as e:
        if e.winerror == 1223:  # the person said no
            return False, "You said no at the Windows prompt, so nothing changed."
        return False, "Windows couldn't start the setup."
    handle = info["hProcess"]
    if win32event.WaitForSingleObject(handle, int(timeout * 1000)) != win32event.WAIT_OBJECT_0:
        return False, "The setup didn't finish in time."
    code = win32process.GetExitCodeProcess(handle)
    if code == 5:
        return False, "Set this up from your own Windows account: it must be an administrator."
    return code == 0, "" if code == 0 else "The setup didn't finish."


def install() -> tuple[bool, str]:
    if not account_is_admin():
        return False, "Your Windows account isn't an administrator, so this can't be set up here."
    ok, why = _elevated(setup_script(current_user()))
    if ok and installed():
        return True, "Set up. Autopilot can now run these repairs without the Windows prompt."
    return False, why or "The setup didn't finish, so nothing is switched on."


def remove() -> tuple[bool, str]:
    if not script_path().exists() and not tasks_present():
        return True, "Removed."
    ok, why = _elevated(remove_script())
    if ok and not script_path().exists():
        return True, "Removed. Admin repairs ask through the Windows prompt again."
    return False, why or "I couldn't remove the setup. It's switched off in the app, but the tasks are still installed."


def tasks_present() -> bool:
    if sys.platform != "win32":
        return False
    schtasks = str(Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "schtasks.exe")
    try:
        r = subprocess.run([schtasks, "/Query", "/TN", task_name(UNATTENDED[0])], capture_output=True, timeout=20,
                           creationflags=CREATE_NO_WINDOW)
        return r.returncode == 0
    except (OSError, subprocess.TimeoutExpired):
        return False


def status(enabled: bool) -> dict:
    return {"enabled": bool(enabled), "installed": installed(), "account_is_admin": account_is_admin(),
            "repairs": [WORDS[e] for e in UNATTENDED]}
